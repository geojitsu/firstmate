#!/usr/bin/env bash
# One-time per-home setup for the captain-input screenshot-drop channel
# (Phase 1). Unlike Relay, this is not wired into bootstrap's continuous
# convergence sweep: firstmate runs this once to turn the channel on, and the
# channel's inertness when never run is structural, not a runtime check - an
# unregistered state/captain-input.check.sh is simply never executed by the
# watcher (bin/fm-watch.sh's *.check.sh sweep, AGENTS.md section 7's custom
# check contract).
#
# Idempotent: safe to re-run. Each step is:
#   1. Write config/captain-input, an empty gitignored presence-flag marker
#      (same convention as config/herdr-presentation-spaces) recording opt-in.
#   2. Create state/captain-drop/ and state/captain-drop/.consumed/ at mode
#      0700, owned by the account this process runs as - the complete
#      authorization boundary per the design report's security posture (SSH
#      auth to this account already gates who can write there).
#   3. Write or refresh the fast-cadence env file the watcher sources at
#      process start: if config/x-mode.env already exists (Relay is on for
#      this home), its FM_CHECK_INTERVAL is reused and nothing new is written;
#      otherwise config/captain-input.env is written with FM_CHECK_INTERVAL=15,
#      the verified cadence floor (bin/fm-watch.sh's main loop only gates the
#      *.check.sh sweep at POLL=${FM_POLL:-15} seconds regardless of a lower
#      FM_CHECK_INTERVAL - see docs/configuration.md "Captain input").
#   4. Write state/captain-input.check.sh, a small trampoline that execs
#      bin/fm-captain-input-watch.sh, then bind its bytes with
#      bin/fm-check-register.sh so the watcher will run it.
#
# Usage: fm-captain-input-enable.sh
set -u

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FM_ROOT="${FM_ROOT_OVERRIDE:-$(cd "$SCRIPT_DIR/.." && pwd)}"
FM_HOME="${FM_HOME:-${FM_ROOT_OVERRIDE:-$FM_ROOT}}"
STATE="${FM_STATE_OVERRIDE:-$FM_HOME/state}"
CONFIG="${FM_CONFIG_OVERRIDE:-$FM_HOME/config}"

fail() {
  printf 'fm-captain-input-enable.sh: %s\n' "$1" >&2
  exit 1
}

mkdir -p "$STATE" "$CONFIG" 2>/dev/null || fail "cannot create $STATE or $CONFIG"

# --- 1. presence-flag marker -------------------------------------------------

FLAG="$CONFIG/captain-input"
if [ ! -e "$FLAG" ] && [ ! -L "$FLAG" ]; then
  TMP=$(mktemp "$CONFIG/.captain-input.XXXXXX") || fail "cannot create temp marker"
  chmod 600 "$TMP" || { rm -f -- "$TMP"; fail "cannot chmod temp marker"; }
  mv -f -- "$TMP" "$FLAG" || fail "cannot publish $FLAG"
fi

# --- 2. drop directories at mode 0700 ---------------------------------------

DROP_DIR="$STATE/captain-drop"
CONSUMED_DIR="$DROP_DIR/.consumed"

ensure_private_dir() {
  local dir=$1
  if [ -e "$dir" ] || [ -L "$dir" ]; then
    [ -d "$dir" ] && [ ! -L "$dir" ] || fail "$dir exists and is not a plain directory"
  else
    ( umask 077; mkdir -- "$dir" ) || fail "cannot create $dir"
  fi
  chmod 700 "$dir" || fail "cannot chmod $dir to 700"
}

ensure_private_dir "$DROP_DIR"
ensure_private_dir "$CONSUMED_DIR"

# --- 3. fast-cadence env file -------------------------------------------------

if [ -e "$CONFIG/x-mode.env" ] || [ -L "$CONFIG/x-mode.env" ]; then
  echo "CAPTAIN_INPUT: reusing config/x-mode.env's cadence (X mode already fast-polls this home)"
else
  CADENCE="$CONFIG/captain-input.env"
  CADENCE_BODY=$(cat <<'EOF'
# Auto-generated by fm-captain-input-enable.sh - captain-input watcher cadence.
# Source this before the active harness protocol starts a watcher process so
# fm-watch.sh polls the captain-input check every 15s (the verified cadence
# floor - see docs/configuration.md "Captain input"). Homes without this file
# (or config/x-mode.env) keep the default 300s cadence.
export FM_CHECK_INTERVAL=15
EOF
)
  TMP=$(mktemp "$CONFIG/.captain-input.env.XXXXXX") || fail "cannot create temp cadence file"
  printf '%s\n' "$CADENCE_BODY" > "$TMP" || { rm -f -- "$TMP"; fail "cannot write temp cadence file"; }
  chmod 600 "$TMP" || { rm -f -- "$TMP"; fail "cannot chmod temp cadence file"; }
  mv -f -- "$TMP" "$CADENCE" || fail "cannot publish $CADENCE"
fi

# --- 4. registered check script ----------------------------------------------

CHECK="$STATE/captain-input.check.sh"
CHECK_BODY=$(cat <<EOF
#!/usr/bin/env bash
# Auto-generated by fm-captain-input-enable.sh. Do not hand-edit: re-run that
# script to refresh this trampoline, then re-register it. Delegates to the
# trusted repository script, mirroring how state/x-watch.check.sh execs
# bin/fm-x-poll.sh - only this file's own bytes are hash-bound.
exec "$FM_ROOT/bin/fm-captain-input-watch.sh" "\$@"
EOF
)
TMP=$(mktemp "$STATE/.captain-input.check.XXXXXX") || fail "cannot create temp check script"
printf '%s\n' "$CHECK_BODY" > "$TMP" || { rm -f -- "$TMP"; fail "cannot write temp check script"; }
chmod 700 "$TMP" || { rm -f -- "$TMP"; fail "cannot chmod temp check script"; }
mv -f -- "$TMP" "$CHECK" || fail "cannot publish $CHECK"

"$SCRIPT_DIR/fm-check-register.sh" captain-input || fail "cannot register $CHECK"

echo "CAPTAIN_INPUT: enabled - config/captain-input, state/captain-drop/, state/captain-input.check.sh registered"
